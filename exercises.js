let currentIndex = 0;

function initNavigation() {
  const nav = document.getElementById("exerciseNav");
  nav.innerHTML = "";

  exercises.forEach((_, index) => {
    const square = document.createElement("button");
    square.className = "nav-square";
    square.title = `Übung ${index + 1}`;
    square.setAttribute("aria-label", `Übung ${index + 1}`);

    // Bild N1.jpg, N2.jpg, ... als Hintergrund festlegen
    square.style.backgroundImage = `url('N${index + 1}.jpeg')`;
    
    square.addEventListener("click", () => {
      currentIndex = index;
      renderExercise();
    });

    nav.appendChild(square);
  });
}

function renderExercise() {
  const ex = exercises[currentIndex];

  // 1. Titel setzen
  document.getElementById("title").innerText = ex.title;

  // 2. JPG-Bilder zentriert rendern
  const galleryGrid = document.getElementById("galleryGrid");
  galleryGrid.innerHTML = "";
  ex.images.forEach((imgSrc, idx) => {
    const container = document.createElement("div");
    container.className = "img-container";

    const img = document.createElement("img");
    img.src = imgSrc;
    img.alt = `${ex.title} - Bild ${idx + 1}`;

    container.appendChild(img);
    galleryGrid.appendChild(container);
  });

  // 3. Video aktualisieren
  const video = document.getElementById("video");
  const videoSource = document.getElementById("videoSource");
  videoSource.src = ex.videoUrl;
  video.load();

  // 4. Textbereich (2-spaltige Nummerierung) rendern
  const textList = document.getElementById("textList");
  textList.innerHTML = "";
  ex.steps.forEach((stepText) => {
    const li = document.createElement("li");
    li.innerText = stepText;
    textList.appendChild(li);
  });

  // 5. Audio-Player für Audiodeskription aktualisieren
  const audioPlayer = document.getElementById("audioPlayer");
  const audioSource = document.getElementById("audioSource");

  if (ex.audioUrl) {
    audioSource.src = ex.audioUrl;
    audioPlayer.load();
    audioPlayer.style.display = "block";
  } else {
    audioPlayer.style.display = "none";
  }

  // 6. Navigation-Aktualisierung
  const squares = document.querySelectorAll(".nav-square");
  squares.forEach((sq, idx) => {
    sq.classList.toggle("active", idx === currentIndex);
  });
}



initNavigation();
renderExercise();